import { mkdir, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { course, lessons, characters, components } from "../app/data/catalog.ts";
import { lessonVisuals } from "../app/data/illustrations.ts";

const output = resolve(
  import.meta.dirname,
  "../wechat-miniprogram/miniprogram/data/catalog.ts",
);

const compactLessons = lessons.map((lesson) => ({
  ...lesson,
  visualPath: lessonVisuals[lesson.id]?.src ?? "",
}));

const compactCharacters = characters.map((character) => ({
  id: character.id,
  lessonId: character.lessonId,
  lessonTitle: character.lessonTitle,
  lessonPosition: character.lessonPosition,
  word: character.word,
  hanzi: character.hanzi,
  pinyin: character.pinyin,
  charType: character.charType,
  decomposition: character.decomposition,
  curriculumRole: character.curriculumRole ?? "extension",
  primary: character.primary,
  ready: character.ready,
  tier: character.tier ?? "curriculum",
}));

const compactComponents = components.map((component) => ({
  id: component.id,
  title: component.title,
  glyph: component.glyph,
  examples: component.examples,
  description: component.description,
  characterSet: component.characterSet,
  group: component.group,
  sequence: component.sequence,
}));

const source = `/* Generated by scripts/generate-miniprogram-catalog.mjs. Do not edit. */
export const catalogSchemaVersion = 1;
export const course = ${JSON.stringify(course, null, 2)};
export const lessons = ${JSON.stringify(compactLessons, null, 2)};
export const characters = ${JSON.stringify(compactCharacters, null, 2)};
export const components = ${JSON.stringify(compactComponents, null, 2)};
`;

await mkdir(dirname(output), { recursive: true });
await writeFile(output, source, "utf8");
process.stdout.write(`Generated WeChat catalog: ${compactLessons.length} lessons, ${compactCharacters.length} characters, ${compactComponents.length} components.\n`);
