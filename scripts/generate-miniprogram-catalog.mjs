import { createHash } from "node:crypto";
import { mkdir, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { course, lessons, characters, components } from "../app/data/catalog.ts";
import { lessonVisuals } from "../app/data/illustrations.ts";
import { lessonDocuments } from "../app/data/lesson-documents.ts";
import { loadLessonMedia } from "../app/data/lesson-media.ts";
import { catalogOrigin, catalogSchemaVersion } from "../app/domain/catalog-contract.ts";
import { skillDimensions } from "../app/domain/learning-state.ts";
import { narrationMedia } from "../app/domain/narration-media.ts";
import { learningTrackIds, trackMeta } from "../app/domain/tracks.ts";

const output = resolve(
  import.meta.dirname,
  "../wechat-miniprogram/miniprogram/data/catalog.ts",
);
const contractOutput = resolve(
  import.meta.dirname,
  "../wechat-miniprogram/miniprogram/data/runtime-contract.ts",
);

const compactLessons = lessons.map((lesson) => ({
  ...lesson,
  visualPath: lessonVisuals[lesson.id]?.src ?? "",
}));

const compactCharacters = characters.map((character) => ({
  id: character.id,
  lessonId: character.lessonId,
  lessonTitle: character.lessonTitle,
  lessonPosition: character.lessonPosition,
  word: character.word,
  hanzi: character.hanzi,
  pinyin: character.pinyin,
  charType: character.charType,
  decomposition: character.decomposition,
  curriculumRole: character.curriculumRole ?? "extension",
  primary: character.primary,
  ready: character.ready,
  tier: character.tier ?? "curriculum",
}));

const compactComponents = components.map((component) => ({
  id: component.id,
  title: component.title,
  glyph: component.glyph,
  examples: component.examples,
  description: component.description,
  characterSet: component.characterSet,
  group: component.group,
  sequence: component.sequence,
}));

const lessonMedia = Object.fromEntries(await Promise.all(
  lessons.map(async (lesson) => [lesson.id, await loadLessonMedia(lesson.id) ?? {}]),
));
const narrationContract = Object.fromEntries(characters.map((character) => {
  const media = lessonMedia[character.lessonId]?.[character.id];
  return [
    character.id,
    narrationMedia(
      character.id,
      media?.transcript ?? character.description,
      character.description,
    ),
  ];
}));

const catalogContentVersion = createHash("sha256")
  .update(JSON.stringify({
    course,
    lessons,
    characters,
    components,
    lessonVisuals,
    lessonDocuments,
    lessonMedia,
    narrationContract,
  }))
  .digest("hex")
  .slice(0, 16);
const trackOrigins = Object.fromEntries(
  learningTrackIds.map((track) => [track, trackMeta[track].origin]),
);

const contractSource = `/* Generated by scripts/generate-miniprogram-catalog.mjs. Do not edit. */
export const catalogSchemaVersion = ${catalogSchemaVersion};
export const catalogContentVersion = ${JSON.stringify(catalogContentVersion)};
export const catalogOrigin = ${JSON.stringify(catalogOrigin)};
export const skillDimensions = ${JSON.stringify(skillDimensions)} as const;
export const learningTrackIds = ${JSON.stringify(learningTrackIds)} as const;
export const trackOrigins = ${JSON.stringify(trackOrigins)} as const;
`;
const source = `/* Generated by scripts/generate-miniprogram-catalog.mjs. Do not edit. */
export const course = ${JSON.stringify(course, null, 2)};
export const lessons = ${JSON.stringify(compactLessons, null, 2)};
export const characters = ${JSON.stringify(compactCharacters, null, 2)};
export const components = ${JSON.stringify(compactComponents, null, 2)};
`;

await mkdir(dirname(output), { recursive: true });
await Promise.all([
  writeFile(output, source, "utf8"),
  writeFile(contractOutput, contractSource, "utf8"),
]);
process.stdout.write(
  `Generated WeChat catalog ${catalogContentVersion}: ${compactLessons.length} lessons, `
  + `${compactCharacters.length} characters, ${compactComponents.length} components.\n`,
);
