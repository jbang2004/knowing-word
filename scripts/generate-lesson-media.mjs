import { mkdir, writeFile } from "node:fs/promises";
import { join, resolve } from "node:path";
import { characters, lessons } from "../app/data/catalog.ts";
import { heritageAssets } from "../app/data/heritage-assets.ts";
import { characterVisuals, getVisualOption } from "../app/data/illustrations.ts";
import { getMnemonicScene } from "../app/data/mnemonic-scenes.ts";
import { releasedNarrationTranscripts } from "../app/data/released-narration-transcripts.generated.ts";
import { getTrackExercises, stableOptionOrder } from "../app/domain/practice.ts";

const projectRoot = resolve(import.meta.dirname, "..");
const mediaRoot = join(projectRoot, "app/data/generated/grade5-volume1/media");
const loaderPath = join(projectRoot, "app/data/generated/grade5-volume1/media-loaders.ts");
const tracks = ["words", "split", "honglan", "structure"];

function practiceOptionVisuals(character) {
  const entries = [];
  for (const track of tracks) {
    for (const question of getTrackExercises(character, track)) {
      if (question.questionType !== "image_single_select") continue;
      const options = stableOptionOrder(question.options, question.id);
      for (const [index, option] of options.entries()) {
        const wrongSlot = options.slice(0, index).filter((item) => !item.correct).length;
        const visual = getVisualOption(
          character.hanzi,
          question.id,
          option.correct,
          wrongSlot,
          option.text,
        );
        if (visual) entries.push([`${question.id}:${option.id}`, visual]);
      }
    }
  }
  return Object.fromEntries(entries);
}

await mkdir(mediaRoot, { recursive: true });
for (const lesson of lessons) {
  const records = Object.fromEntries(
    characters
      .filter((character) => character.lessonId === lesson.id)
      .map((character) => [character.id, {
        visual: characterVisuals[character.hanzi],
        heritage: heritageAssets[character.id],
        scene: getMnemonicScene(character),
        transcript: releasedNarrationTranscripts[character.id]?.transcript || character.description,
        practiceOptionVisuals: practiceOptionVisuals(character),
      }]),
  );
  await writeFile(
    join(mediaRoot, `${lesson.id}.ts`),
    `/* Generated by scripts/generate-lesson-media.mjs. Do not edit by hand. */\n`
      + `import type { LessonCharacterMedia } from "../../../lesson-media-types.ts";\n\n`
      + `export const characterMedia = ${JSON.stringify(records, null, 2)} satisfies Record<string, LessonCharacterMedia>;\n`,
  );
}

const loaders = lessons
  .map((lesson) => `  "${lesson.id}": () => import("./media/${lesson.id}.ts"),`)
  .join("\n");
await writeFile(
  loaderPath,
  `/* Generated by scripts/generate-lesson-media.mjs. Do not edit by hand. */\n`
    + `export const lessonMediaLoaders = {\n${loaders}\n} as const;\n`,
);
process.stdout.write(`Generated ${lessons.length} bounded lesson media shards.\n`);
