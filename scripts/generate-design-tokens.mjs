import { readFile, writeFile } from "node:fs/promises";
import { resolve } from "node:path";

const root = resolve(import.meta.dirname, "..");
const tokens = JSON.parse(await readFile(resolve(root, "config/design-tokens.json"), "utf8"));

function declarations(values) {
  return Object.entries(values).map(([name, value]) => `  --${name}: ${value};`).join("\n");
}

const web = `/* Generated by scripts/generate-design-tokens.mjs. Do not edit. */
:root {
${declarations({ ...tokens.light, ...tokens.aliases, ...tokens.shared })}
  --kai: "Knowing Kai", "Kaiti SC", "STKaiti", KaiTi, "Songti SC", STSong, serif;
  --serif: "Iowan Old Style", "Source Han Serif SC", "Noto Serif CJK SC", "Songti SC", STSong, Georgia, serif;
  --sans: "PingFang SC", "Hiragino Sans GB", "Microsoft YaHei", system-ui, sans-serif;
  --round: ui-rounded, "SF Pro Rounded", "Hiragino Maru Gothic ProN", var(--sans);
}

html[data-theme="night"] {
${declarations({ ...tokens.dark, ...tokens.darkShared })}
}
`;

const mini = `/* Generated by scripts/generate-design-tokens.mjs. Do not edit. */
page {
${declarations({ ...tokens.light, ...tokens.aliases, ...tokens.shared })}
  --page-gutter: 16px;
  --tap-size: 44px;
  --tabbar-height: 72px;
  --font-kai: "Knowing Kai", "Kaiti SC", STKaiti, KaiTi, "Songti SC", STSong, serif;
  --font-serif: "Iowan Old Style", "Source Han Serif SC", "Noto Serif CJK SC", "Songti SC", STSong, Georgia, serif;
  --font-sans: "PingFang SC", "Hiragino Sans GB", "Microsoft YaHei", system-ui, sans-serif;
  --font-round: ui-rounded, "SF Pro Rounded", "Hiragino Maru Gothic ProN", "PingFang SC", sans-serif;
}

.theme-night {
${declarations({ ...tokens.dark, ...tokens.darkShared })}
}
`;

const outputs = [
  [resolve(root, "app/design-tokens.generated.css"), web],
  [resolve(root, "wechat-miniprogram/miniprogram/design-tokens.generated.wxss"), mini],
];

if (process.argv.includes("--check")) {
  const current = await Promise.all(outputs.map(([path]) => readFile(path, "utf8")));
  const stale = outputs.filter(([, expected], index) => current[index] !== expected).map(([path]) => path);
  if (stale.length) throw new Error(`Generated design tokens are stale: ${stale.join(", ")}`);
} else {
  await Promise.all(outputs.map(([path, contents]) => writeFile(path, contents, "utf8")));
}
