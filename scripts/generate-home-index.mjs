import { writeFile } from "node:fs/promises";
import { resolve } from "node:path";
import { characters, course, lessons } from "../app/data/catalog.ts";

const origins = {
  words: "识字小测",
  split: "拆一拆",
  honglan: "红蓝字",
  structure: "空间结构",
};

const candidates = Object.fromEntries(
  Object.entries(origins).map(([track, origin]) => [
    track,
    characters
      .filter(
        (character) =>
          character.primary &&
          character.official !== false &&
          character.exercises.some((exercise) => exercise.origin === origin),
      )
      .map(({ id, lessonId, hanzi }) => ({ id, lessonId, hanzi })),
  ]),
);

const candidateGroups = [];
const candidateGroupByTrack = {};
for (const [track, trackCandidates] of Object.entries(candidates)) {
  const serialized = JSON.stringify(trackCandidates);
  let groupIndex = candidateGroups.findIndex((group) => group.serialized === serialized);
  if (groupIndex === -1) {
    groupIndex = candidateGroups.length;
    candidateGroups.push({ serialized, candidates: trackCandidates });
  }
  candidateGroupByTrack[track] = groupIndex;
}

const candidateDeclarations = candidateGroups
  .map((group, index) => `const candidateGroup${index}: HomeCandidate[] = ${JSON.stringify(group.candidates, null, 2)};`)
  .join("\n\n");
const candidateAssignments = Object.keys(origins)
  .map((track) => `  ${track}: candidateGroup${candidateGroupByTrack[track]},`)
  .join("\n");

const source = `/* Generated by scripts/generate-home-index.mjs. Do not edit by hand. */
export type HomeTrackId = "words" | "split" | "honglan" | "structure";
export type HomeCandidate = { id: string; lessonId: string; hanzi: string };

export const homeCourse = ${JSON.stringify({
  title: course.title,
  grade: course.grade,
  lessons: lessons.map(({ id, title, position }) => ({ id, title, position })),
}, null, 2)} as const;

${candidateDeclarations}

export const homeCandidates: Record<HomeTrackId, HomeCandidate[]> = {
${candidateAssignments}
};
`;

const routeIndexSource = `/* Generated by scripts/generate-home-index.mjs. Do not edit by hand. */
export const lessonIds = ${JSON.stringify(lessons.map((lesson) => lesson.id), null, 2)} as const;

export const characterLessons: Readonly<Record<string, string>> = ${JSON.stringify(
  Object.fromEntries(characters.map((character) => [character.id, character.lessonId])),
  null,
  2,
)};
`;

await writeFile(
  resolve(import.meta.dirname, "../app/data/home-index.generated.ts"),
  source,
);
await writeFile(
  resolve(import.meta.dirname, "../app/data/route-index.generated.ts"),
  routeIndexSource,
);
process.stdout.write("Wrote compact home learning index.\n");
